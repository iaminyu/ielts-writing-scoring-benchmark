"""Recompute every published metric from data/scores.csv (Python 3 standard library only).

Usage: python3 scripts/compute_metrics.py [dataset_root]
Writes results/metrics.json and results/metrics.md.
"""
import csv, itertools, json, pathlib, random, sys
from decimal import ROUND_HALF_UP, Decimal

ROOT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parents[1]
PLATFORMS = {
    "ielts_writing_practice": "IELTS Writing Practice",
    "ieltswritingchecker_org": "IELTSWritingChecker.org",
    "chatgpt": "ChatGPT",
    "engnovate": "Engnovate",
    "writing9": "Writing9",
}
BOOTSTRAP_ITERATIONS = 10_000
BOOTSTRAP_SEED = 20260830

rows = list(csv.DictReader(open(ROOT / "data/scores.csv", encoding="utf-8")))
assert len(rows) == 97, f"expected 97 responses, found {len(rows)}"


def summarise(subset, platform):
    errors = [float(r[platform]) - float(r["official_band"]) for r in subset]
    n = len(errors)
    return {
        "n": n,
        "mae": sum(abs(e) for e in errors) / n,
        "bias": sum(errors) / n,
        "exact": sum(e == 0 for e in errors),
        "within_0_5": sum(abs(e) <= 0.5 for e in errors),
        "within_1_0": sum(abs(e) <= 1.0 for e in errors),
        "more_than_1_0": sum(abs(e) > 1.0 for e in errors),
    }


SUBSETS = {
    "all": rows,
    "task_1": [r for r in rows if r["task"] == "Task 1"],
    "task_2": [r for r in rows if r["task"] == "Task 2"],
    "academic": [r for r in rows if r["module"] == "Academic"],
    "general_training": [r for r in rows if r["module"] == "General Training"],
    "recent_cambridge_20_21": [r for r in rows if r["recent_cambridge_20_21"] == "yes"],
}
sources = sorted({r["source"] for r in rows})

metrics = {"n": len(rows), "platforms": {}, "paired_mae_differences": []}
for key in PLATFORMS:
    p = {name: summarise(subset, key) for name, subset in SUBSETS.items()}
    p["by_source"] = {s: summarise([r for r in rows if r["source"] == s], key) for s in sources}
    metrics["platforms"][key] = p

# Paired bootstrap of the MAE difference for every pair of platforms (same responses resampled for both).
rng = random.Random(BOOTSTRAP_SEED)
draws = [[rng.randrange(len(rows)) for _ in rows] for _ in range(BOOTSTRAP_ITERATIONS)]
abs_err = {k: [abs(float(r[k]) - float(r["official_band"])) for r in rows] for k in PLATFORMS}
for a, b in itertools.combinations(PLATFORMS, 2):
    diff = [x - y for x, y in zip(abs_err[a], abs_err[b])]
    boots = sorted(sum(diff[i] for i in d) / len(d) for d in draws)
    metrics["paired_mae_differences"].append({
        "a": a, "b": b,
        "mae_difference": sum(diff) / len(diff),
        "ci95": [boots[int(0.025 * BOOTSTRAP_ITERATIONS) - 1], boots[int(0.975 * BOOTSTRAP_ITERATIONS) - 1]],
        "a_closer": sum(d < 0 for d in diff), "tie": sum(d == 0 for d in diff), "b_closer": sum(d > 0 for d in diff),
    })
metrics["bootstrap"] = {"iterations": BOOTSTRAP_ITERATIONS, "seed": BOOTSTRAP_SEED, "method": "paired percentile"}

(ROOT / "results").mkdir(exist_ok=True)
(ROOT / "results/metrics.json").write_text(json.dumps(metrics, indent=1) + "\n")


def half_up(value, places):
    return Decimal(str(value)).quantize(Decimal(1).scaleb(-places), rounding=ROUND_HALF_UP)


def pct(count, n):
    return f"{half_up(Decimal(100 * count) / Decimal(n), 1)}% ({count}/{n})"


lines = ["# Results", "", "Generated by `scripts/compute_metrics.py` from `data/scores.csv`. Do not edit by hand.", ""]
for name, title in (("all", "All 97 responses"), ("task_1", "Task 1"), ("task_2", "Task 2"),
                    ("academic", "Academic"), ("general_training", "General Training"),
                    ("recent_cambridge_20_21", "Cambridge IELTS 20 and 21 only")):
    n = SUBSETS[name].__len__()
    lines += [f"## {title} (n = {n})", "",
              "| Platform | MAE | Signed bias | Exact | Within 0.5 | Within 1.0 | More than 1.0 off |",
              "|---|---|---|---|---|---|---|"]
    for key, label in PLATFORMS.items():
        m = metrics["platforms"][key][name]
        lines.append(f"| {label} | {half_up(m['mae'], 2)} | {half_up(m['bias'], 2):+} | {m['exact']} | {pct(m['within_0_5'], n)} | "
                     f"{pct(m['within_1_0'], n)} | {m['more_than_1_0']} |")
    lines.append("")
lines += ["## Paired MAE differences (all 97 responses)", "",
          f"Difference = MAE of the first platform minus MAE of the second. 95% interval from a paired bootstrap "
          f"({BOOTSTRAP_ITERATIONS:,} resamples, seed {BOOTSTRAP_SEED}). An interval that includes 0 means this "
          "sample cannot separate the two platforms.", "",
          "| First | Second | Difference | 95% interval | First closer | Tie | Second closer |",
          "|---|---|---|---|---|---|---|"]
for d in metrics["paired_mae_differences"]:
    lines.append(f"| {PLATFORMS[d['a']]} | {PLATFORMS[d['b']]} | {d['mae_difference']:+.3f} | "
                 f"{d['ci95'][0]:+.3f} to {d['ci95'][1]:+.3f} | {d['a_closer']} | {d['tie']} | {d['b_closer']} |")
(ROOT / "results/metrics.md").write_text("\n".join(lines) + "\n")
print(f"wrote {ROOT / 'results/metrics.json'} and results/metrics.md")
